#!/usr/bin/env python3
"""Check that the proofs transcribed into the supplement match their Markdown sources.

The supplement reproduces four reviewed Markdown notes between the markers
  % BEGIN TRANSCRIPTION <path> lines <a>-<b> sha256 <digest> commit <commit>
  % END TRANSCRIPTION <path>
For each region this script checks that the source file has the recorded SHA-256, that every
formula of the source lines (inline $`...`$ and ```math blocks) appears in the TeX region in the
same order and byte for byte, and that the words of the surrounding prose agree after markup is
removed. It is an editorial check of the transcription, not a check of the mathematics.

Run from the repository root:  python3 -B paper/checks/check_transcriptions.py
"""
import argparse, hashlib, re, sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
SUPP = ROOT / 'paper' / 'friend-tree-exponent-supplement.tex'
BEGIN = re.compile(r'^% BEGIN TRANSCRIPTION (\S+) lines (\d+)-(\d+) sha256 ([0-9a-f]{64}) commit ([0-9a-f]{40})$')


def md_parts(lines):
    """Return (formulas, words) of Markdown lines."""
    formulas, text = [], []
    i = 0
    while i < len(lines):
        line = lines[i]
        if line.lstrip().startswith('```math'):  # fences may be indented inside list items
            ind = len(line) - len(line.lstrip())
            j = i + 1
            while not lines[j].lstrip().startswith('```'):
                j += 1
            body = [x[ind:] if not x[:ind].strip() else x for x in lines[i + 1:j]]
            formulas.append('\n'.join(body).strip())
            i = j + 1
            continue
        if line.lstrip().startswith('```'):
            j = i + 1
            while not lines[j].lstrip().startswith('```'):
                j += 1
            text.append('\n'.join(lines[i + 1:j]))
            i = j + 1
            continue
        for m in re.finditer(r'\$`(.+?)`\$', line):
            formulas.append(m.group(1).strip())
        stripped = re.sub(r'\$`.+?`\$', ' ', line)
        stripped = re.sub(r'^\s*\d+\.\s', ' ', stripped)  # enumerate numbers are generated by LaTeX
        stripped = re.sub(r'\[([^\]]+)\]\([^)\s]+\)', r'\1', stripped)
        text.append(stripped)
        i += 1
    return formulas, words('\n'.join(text))


def brace_arg(s, k):
    """s[k] == '{'; return (content, index after closing brace)."""
    depth, j = 0, k
    while True:
        c = s[j]
        if c == '\\':
            j += 2
            continue
        if c == '{':
            depth += 1
        elif c == '}':
            depth -= 1
            if depth == 0:
                return s[k + 1:j], j + 1
        j += 1


def md_ordinals(lines):
    """Numbers of ordered-list items, outside code fences (an escaped '1\\.' is not a list item)."""
    out, fence = [], False
    for line in lines:
        if line.lstrip().startswith('```'):
            fence = not fence
            continue
        m = None if fence else re.match(r'^\s*(\d+)\.\s', line)
        if m:
            out.append(int(m.group(1)))
    return out


def tex_ordinals(s):
    """Numbers LaTeX prints for enumerate items in a transcribed region."""
    out, stack = [], []
    for m in re.finditer(r'\\begin\{(enumerate|itemize)\}(?:\\setcounter\{enumi\}\{(\d+)\})?|\\end\{(enumerate|itemize)\}|\\item\b', s):
        if m.group(1):
            stack.append([m.group(1), int(m.group(2) or 0)])
        elif m.group(3):
            stack.pop()
        elif stack and stack[-1][0] == 'enumerate':
            stack[-1][1] += 1
            out.append(stack[-1][1])
    return out


def tex_parts(s):
    """Return (formulas, words) of a transcribed TeX region."""
    formulas, text, i = [], [], 0
    while i < len(s):
        if s.startswith('\\fitdisplay{', i):
            body, i = brace_arg(s, i + len('\\fitdisplay'))
            if body.startswith('\\begin{multlined}[\\linewidth]%\n') and body.endswith('\n\\end{multlined}'):
                # layout-only line breaks in the widest displays
                body = body[len('\\begin{multlined}[\\linewidth]%\n'):-len('\n\\end{multlined}')].replace('\\ftbreak ', '')
            elif body.startswith('%\n'):
                body = body[2:]
            elif body.startswith('\\begin{aligned}\n') and body.endswith('\n\\end{aligned}'):
                body = body[len('\\begin{aligned}\n'):-len('\n\\end{aligned}')]
            formulas.append(body.strip())
            text.append(' ')
            continue
        if s.startswith('\\begin{verbatim}', i):
            j = s.index('\\end{verbatim}', i)
            text.append(s[i + len('\\begin{verbatim}'):j])
            i = j + len('\\end{verbatim}')
            continue
        if s.startswith('\\begin{tabular}{', i):
            _, i = brace_arg(s, i + len('\\begin{tabular}'))  # column specification
            continue
        if s.startswith('\\ensuremath{', i):
            _, i = brace_arg(s, i + len('\\ensuremath'))  # a glyph that replaced a Unicode symbol in prose
            text.append(' ')
            continue
        if s.startswith('\\reviewnote{', i):
            _, i = brace_arg(s, i + len('\\reviewnote'))  # framed review note: an addition, not part of the source
            text.append(' ')
            continue
        m = re.match(r'\\(href|proofsrc|ordersrc)\{', s[i:])
        if m:
            _, i = brace_arg(s, i + len(m.group(0)) - 1)  # link target; the link text follows as ordinary text
            continue
        if s[i] == '\\' and i + 1 < len(s) and s[i + 1] in '$&%#_{}':
            text.append(s[i + 1])
            i += 2
            continue
        if s[i] == '$':
            j = i + 1
            while s[j] != '$':
                j += 2 if s[j] == '\\' else 1
            inner = s[i + 1:j]
            formulas.append(inner.strip())
            text.append(' ')
            i = j + 1
            continue
        text.append(s[i])
        i += 1
    plain = ''.join(text)
    plain = re.sub(r'\\(textbf|emph|texttt|trhead|section\*|subsection\*|subsubsection\*)', ' ', plain)
    plain = re.sub(r'\\(textbackslash|textasciitilde|textasciicircum|dots|S)\{\}', ' ', plain)
    plain = re.sub(r'\\(begin|end)\{(itemize|enumerate|quote|transcription|center|tabular)\}', ' ', plain)
    plain = re.sub(r'\\setcounter\{enumi\}\{\d+\}', ' ', plain)
    plain = re.sub(r'\\(item|toprule|midrule|bottomrule|footnotesize)\b', ' ', plain)
    plain = re.sub(r"\\['\"`]", '', plain)
    return formulas, words(plain)


def words(t):
    import unicodedata
    t = unicodedata.normalize('NFKD', t)
    t = ''.join(c if ord(c) < 128 else ('' if unicodedata.combining(c) else ' ') for c in t)
    t = re.sub(r"[^\w]+", ' ', t, flags=re.ASCII)
    return [w for w in t.split() if w]


def ascii_fold(ws):
    import unicodedata
    out = []
    for w in ws:
        w = unicodedata.normalize('NFKD', w).encode('ascii', 'ignore').decode()
        out += [x for x in re.split(r'[^\w]+', w, flags=re.ASCII) if x]
    return out


def main():
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument('--tex', type=Path, default=SUPP)
    args = ap.parse_args()
    lines = args.tex.read_text(encoding='utf-8').split('\n')
    regions, failures = 0, 0
    i = 0
    while i < len(lines):
        m = BEGIN.match(lines[i])
        if not m:
            i += 1
            continue
        path, a, b, digest, commit = m.group(1), int(m.group(2)), int(m.group(3)), m.group(4), m.group(5)
        j = i + 1
        while not lines[j].startswith('% END TRANSCRIPTION'):
            j += 1
        region = '\n'.join(lines[i + 1:j])
        regions += 1
        src = ROOT / path
        data = src.read_bytes()
        if hashlib.sha256(data).hexdigest() != digest:
            print(f'FAIL {path}: SHA-256 differs from the recorded {digest}')
            failures += 1
        md_f, md_w = md_parts(data.decode('utf-8').split('\n')[a - 1:b])
        tx_f, tx_w = tex_parts(region)
        if md_f != tx_f:
            failures += 1
            k = next((k for k, (x, y) in enumerate(zip(md_f, tx_f)) if x != y), min(len(md_f), len(tx_f)))
            print(f'FAIL {path}: formulas differ (source {len(md_f)}, TeX {len(tx_f)}); first difference at formula {k + 1}')
            print('  source:', (md_f[k] if k < len(md_f) else '<none>')[:200])
            print('  TeX:   ', (tx_f[k] if k < len(tx_f) else '<none>')[:200])
        md_w, tx_w = ascii_fold(md_w), ascii_fold(tx_w)
        if md_w != tx_w:
            failures += 1
            k = next((k for k, (x, y) in enumerate(zip(md_w, tx_w)) if x != y), min(len(md_w), len(tx_w)))
            print(f'FAIL {path}: prose differs (source {len(md_w)} words, TeX {len(tx_w)}); first difference at word {k + 1}')
            print('  source:', ' '.join(md_w[max(0, k - 8):k + 8]))
            print('  TeX:   ', ' '.join(tx_w[max(0, k - 8):k + 8]))
        notes = region.count('\\reviewnote{')
        if notes:
            print(f'note {path}: {notes} framed review note(s) added, excluded from the comparison')
        md_o, tx_o = md_ordinals(data.decode('utf-8').split('\n')[a - 1:b]), tex_ordinals(region)
        if md_o != tx_o:
            failures += 1
            print(f'FAIL {path}: list numbers differ (source {md_o[:20]}..., TeX {tx_o[:20]}...)')
        if md_f == tx_f and md_w == tx_w and md_o == tx_o:
            print(f'ok   {path} lines {a}-{b}: {len(md_f)} formulas, {len(md_w)} words and {len(md_o)} list numbers match (commit {commit[:12]})')
        i = j + 1
    if regions != 4:
        print(f'FAIL: expected 4 transcribed regions, found {regions}')
        failures += 1
    print('RESULT: PASS' if failures == 0 else f'RESULT: FAIL ({failures})')
    return 0 if failures == 0 else 1


if __name__ == '__main__':
    sys.exit(main())
